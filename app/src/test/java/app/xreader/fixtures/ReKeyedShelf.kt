 * package's deleted row — "the whole set's pointers are
 * stale" — the exact input `V1510StableIdentityOpenTest`
 * (L-BC) drives through the B5 resolver: per book, resolution
 * must fall back to the decoded sourceId, find the
 * re-inserted row, and heal the book's pointer to that
 * package's NEW id.
 *
 * The NEGATIVE TWIN rides in the same database: a fifth
 * package is inserted, a book stored against it the same way,
 * and the package row is then deleted and NEVER re-inserted —
 * its sourceId is declared by no installed row, so the honest
 * named "genuinely gone" state is the only correct outcome.
 */
