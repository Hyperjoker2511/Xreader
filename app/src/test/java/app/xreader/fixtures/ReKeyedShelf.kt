 * owner scope 2026-11-06 03:57 IST): the RE-KEYED extension
 * shelf — the stale-pointer state behind the owner's failure,
 * which is ALL manga across ALL Keiyoushi sources at once,
 * not one book.
 *
 * Built by LITERALLY performing the accident on a real Room
 * database (not by hand-writing the end state):
 *
 *  1. FOUR distinct KEIYOUSHI package rows are INSERTED, each
 *     taking an autogenerated row id ([ReKeyedBook.oldExtensionId]);
 *  2. a book per package is stored against THAT row id, its
 *     `remoteId` carrying the stable identity in the tree's
 *     own encoding — [SourceBookIds.encode] of (sourceId,
 *     bookRemoteId) — plus its chapter rows;
 *  3. ALL FOUR package rows are DELETED in the same pass;
 *  4. the SAME packages (same `packageId`s, same declared
 *     `sourceIds`, same record shape the shelf builds) are
 *     RE-INSERTED, each taking a NEW autogenerated row id
 *     ([ReKeyedBook.newExtensionId], asserted ≠ its old id).
