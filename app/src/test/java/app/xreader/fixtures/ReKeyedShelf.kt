    /** Performs the whole-set delete + re-insert accident
     * and returns the shelf with every row id recorded. */
    suspend fun build(context: Context): Built {
        val db = Room.inMemoryDatabaseBuilder(
            context, XreaderDatabase::class.java
        ).allowMainThreadQueries().build()

        val oldIds = LinkedHashMap<String, Long>()
        val newIds = LinkedHashMap<String, Long>()
        var orphanId = -1L
        db.withTransaction {
            db.extensionRepoDao().insert(
                ExtensionRepo(
                    id = REPO_ID, name = "Re-Keyed Fixture Repo",
                    indexUrl = "https://example.test/index.json",
                    lastFetchedAt = LEGACY_TIME
                )
            )
            val extDao = db.installedExtensionDao()
            val bookDao = db.bookDao()
            val chapterDao = db.chapterDao()

            // (1)+(2): every package as first installed, each
            // with its book stored against its autogenerated
            // row id.
            for (spec in SPECS) {
                val oldId = extDao.insert(
                    keiyoushiRow(
                        spec.displayName, spec.packageId,
                        listOf(spec.sourceId)
                    )
                )
                oldIds[spec.packageId] = oldId
                bookDao.insert(
                    book(spec.bookId, spec.bookTitle, oldId,
                        spec.encodedRemoteId, spec.chapters)
                )
                chapterDao.insertAll(chapters(spec.bookId, spec.chapters))
            }
            // A decoy row after them, so no re-insert below
            // can be handed a deleted row's id back by rowid
            // reuse — every new id must be genuinely NEW.
            extDao.insert(
                keiyoushiRow(
                    "Decoy Panels",
                    "eu.kanade.tachiyomi.extension.en.decoypanels",
                    listOf("7777777777777777777")
                )
            )
            // The negative twin's package + book, same shape.
            orphanId = extDao.insert(
                keiyoushiRow(
                    "Gone Comics", ORPHAN_PACKAGE_ID,
                    listOf(ORPHAN_SOURCE_ID)
                )
            )
            bookDao.insert(
                book(ORPHAN_BOOK_ID, "Orphan Fixture Book", orphanId,
                    ORPHAN_ENCODED_BOOK_REMOTE_ID, 1)
            )
            chapterDao.insertAll(chapters(ORPHAN_BOOK_ID, 1))

            // (3): ALL the packages' rows are deleted in the
            // same pass — the whole set at once…
            for (spec in SPECS) {
                extDao.delete(extDao.getById(oldIds.getValue(spec.packageId))!!)
            }
            extDao.delete(extDao.getById(orphanId)!!)

            // (4): …and every package EXCEPT the orphan comes
            // back — same packageId, same sourceIds, NEW ids.
            for (spec in SPECS) {
                newIds[spec.packageId] = extDao.insert(
                    keiyoushiRow(
                        spec.displayName, spec.packageId,
                        listOf(spec.sourceId)
                    )
                )
            }
        }
        val reKeyed = SPECS.map { spec ->
            val oldId = oldIds.getValue(spec.packageId)
            val newId = newIds.getValue(spec.packageId)
            check(newId > 0 && newId != oldId && newId !in oldIds.values) {
                "re-inserted package ${spec.packageId} must take " +
                    "a NEW row id (old=$oldId, new=$newId)"
            }
            ReKeyedBook(spec, oldId, newId)
        }
        return Built(db, reKeyed, orphanId)
    }
